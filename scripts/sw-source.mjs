// Generates sw.js: the offline cache for the installed app.
// The precache list is read from the code (index.html, the module graph, the combat worker),
// and the cache name is a hash of every precached file, so any change ships as an update.
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFileSync(resolve(ROOT, file));
const fileOf = url => url.replace(/^\.?\//, '').split('?')[0];

export function precacheList() {
  const html = read('index.html').toString();
  const urls = new Set(['./', './index.html', './manifest.json', './icons/icon-192.png', './icons/icon-512.png', './icons/apple-touch-icon.png']);
  for (const [, url] of html.matchAll(/(?:href|src)="(\.\/[^"]+\.(?:css|js)(?:\?[^"]*)?)"/g)) urls.add(url);
  // Follow static imports (and the combat worker) from the entry module.
  const queue = [...urls].filter(url => /\.js(\?|$)/.test(url));
  while (queue.length) {
    const source = read(fileOf(queue.shift())).toString();
    const found = [
      ...[...source.matchAll(/^\s*(?:import|export)\s[^;]*?from\s*['"](\.\/[^'"]+)['"]/gms)].map(m => m[1]),
      ...[...source.matchAll(/new Worker\(\s*['"]\/?([^'"]+)['"]/g)].map(m => './' + m[1].replace(/^\.\//, '')),
    ];
    for (const url of found)
      if (!urls.has(url)) {
        urls.add(url);
        queue.push(url);
      }
  }
  return [...urls].sort();
}
export function swSource() {
  const list = precacheList();
  const hash = createHash('sha256');
  for (const url of list) if (url !== './') hash.update(url).update(read(fileOf(url)));
  const version = hash.digest('hex').slice(0, 12);
  return `// Generated by scripts/build-sw.mjs — do not edit by hand. Run: npm run build
// Offline cache for the installed Twesk app. Pages load from the network when the local server is
// running (falling back to the cache when it is not); versioned files load from the cache first.
const CACHE = 'twesk-${version}';
const PRECACHE = ${JSON.stringify(list, null, 2)};

self.addEventListener('install', event => {
  // cache: 'reload' skips the browser's HTTP cache, so the offline copy is always the current version.
  event.waitUntil(
    caches
      .open(CACHE)
      .then(cache => cache.addAll(PRECACHE.map(url => new Request(url, { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});
self.addEventListener('activate', event => {
  event.waitUntil(
    caches
      .keys()
      .then(keys => Promise.all(keys.filter(key => key.startsWith('twesk-') && key !== CACHE).map(key => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      // Always ask the server for the page (never a stale HTTP-cached copy); fall back offline.
      fetch(request, { cache: 'no-cache' })
        .then(response => {
          const copy = response.clone();
          if (response.ok) caches.open(CACHE).then(cache => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html')),
    );
    return;
  }
  event.respondWith(
    caches.match(request).then(
      cached =>
        cached ||
        fetch(request).then(response => {
          if (response.ok) {
            const copy = response.clone();
            caches.open(CACHE).then(cache => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
}
